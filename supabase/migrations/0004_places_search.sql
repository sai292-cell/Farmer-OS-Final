CREATE OR REPLACE FUNCTION public.place_name_key(value text)
RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = public, extensions, pg_catalog
AS $$
  WITH normal AS (
    SELECT regexp_replace(
      regexp_replace(
        regexp_replace(
          regexp_replace(
            regexp_replace(
              regexp_replace(
                regexp_replace(
                  regexp_replace(
                    regexp_replace(
                      regexp_replace(
                        regexp_replace(lower(extensions.unaccent(coalesce(value, ''))), 'ph', 'f', 'g'),
                        'ck', 'k', 'g'
                      ), 'ee', 'i', 'g'
                    ), 'oo', 'u', 'g'
                  ), 'aa', 'a', 'g'
                ), 'th', 't', 'g'
              ), 'dh', 'd', 'g'
            ), 'kh', 'k', 'g'
          ), 'gh', 'g', 'g'
        ), 'sh', 's', 'g'
      ), 'ch', 'c', 'g'
    ) AS value
  ), letters AS (
    SELECT regexp_replace(translate(value, 'zw', 'jv'), '[^a-z]', '', 'g') AS value
    FROM normal
  ), collapsed AS (
    SELECT regexp_replace(value, '(.)\1+', '\1', 'g') AS value
    FROM letters
  )
  SELECT CASE
    WHEN value = '' THEN ''
    ELSE left(value, 1) || regexp_replace(substr(value, 2), '[aeiou]', '', 'g')
  END
  FROM collapsed;
$$;

