CREATE OR REPLACE FUNCTION public.search_places(
  q text,
  near_lat double precision DEFAULT NULL,
  near_lng double precision DEFAULT NULL,
  max_results integer DEFAULT 8
)
RETURNS TABLE (
  id bigint, name text, name_local text, place_type text, district text, state text,
  population integer, lat double precision, lng double precision, match_level text, score double precision
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public, extensions, pg_catalog
AS $$
  WITH input AS (
    SELECT trim(q) AS query, lower(extensions.unaccent(trim(q))) AS normalized,
      public.place_name_key(trim(q)) AS skeleton
  ), candidates AS (
    SELECT p.*, ST_Y(p.location::geometry) AS lat, ST_X(p.location::geometry) AS lng,
      CASE
        WHEN lower(extensions.unaccent(p.name)) = i.normalized THEN 1.0
        WHEN lower(extensions.unaccent(p.name)) LIKE i.normalized || '%' THEN 0.9
        WHEN i.skeleton <> '' AND p.name_key = i.skeleton THEN 0.86
        WHEN p.name_local ILIKE '%' || i.query || '%' OR EXISTS (
          SELECT 1 FROM unnest(p.alt_names) alt WHERE alt ILIKE '%' || i.query || '%'
        ) THEN 0.82
        ELSE greatest(similarity(lower(extensions.unaccent(p.name)), i.normalized),
          (SELECT coalesce(max(similarity(keys, i.skeleton)), 0) FROM unnest(p.name_keys) keys))
      END AS quality,
      CASE WHEN p.place_type IN ('village', 'hamlet', 'locality') THEN 0.04
           WHEN p.place_type IN ('taluka', 'district') THEN 0.01 ELSE 0 END AS type_bonus,
      CASE WHEN near_lat IS NOT NULL AND near_lng IS NOT NULL
        THEN ST_Distance(p.location, ST_SetSRID(ST_MakePoint(near_lng, near_lat), 4326)::geography) / 1000000.0
        ELSE 0 END AS distance_penalty
    FROM public.places p CROSS JOIN input i
    WHERE char_length(i.query) >= 2
      AND (lower(extensions.unaccent(p.name)) LIKE i.normalized || '%'
        OR similarity(lower(extensions.unaccent(p.name)), i.normalized) >= 0.18
        OR (i.skeleton <> '' AND (p.name_key = i.skeleton OR EXISTS (SELECT 1 FROM unnest(p.name_keys) keys WHERE similarity(keys, i.skeleton) >= 0.55)))
        OR p.name_local ILIKE '%' || i.query || '%'
        OR EXISTS (SELECT 1 FROM unnest(p.alt_names) alt WHERE alt ILIKE '%' || i.query || '%')
        OR lower(extensions.unaccent(coalesce(p.district, ''))) LIKE i.normalized || '%')
  )
  SELECT id, name, name_local, place_type, district, state, population, lat, lng,
    CASE WHEN quality >= 0.99 THEN 'exact' WHEN quality >= 0.8 THEN 'close' ELSE 'similar' END,
    quality + type_bonus - distance_penalty
  FROM candidates
  ORDER BY quality DESC, distance_penalty ASC,
    CASE place_type WHEN 'village' THEN 1 WHEN 'hamlet' THEN 2 WHEN 'locality' THEN 3 WHEN 'town' THEN 4 WHEN 'city' THEN 5 WHEN 'taluka' THEN 6 WHEN 'district' THEN 7 ELSE 8 END,
    population DESC NULLS LAST
  LIMIT least(greatest(coalesce(max_results, 8), 1), 15);
$$;

REVOKE ALL ON FUNCTION public.search_places(text, double precision, double precision, integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.search_places(text, double precision, double precision, integer) TO authenticated;
