CREATE OR REPLACE FUNCTION public.prepare_place_keys()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, extensions, pg_catalog
AS $$
DECLARE
  candidate text;
BEGIN
  NEW.name_key := public.place_name_key(NEW.name);
  NEW.name_keys := ARRAY[NEW.name_key];
  FOREACH candidate IN ARRAY coalesce(NEW.alt_names, '{}') || ARRAY[coalesce(NEW.name_local, '')]
  LOOP
    IF nullif(trim(candidate), '') IS NOT NULL THEN
      NEW.name_keys := array_append(NEW.name_keys, public.place_name_key(candidate));
    END IF;
  END LOOP;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS places_prepare_keys ON public.places;
CREATE TRIGGER places_prepare_keys
BEFORE INSERT OR UPDATE OF name, name_local, alt_names ON public.places
FOR EACH ROW EXECUTE FUNCTION public.prepare_place_keys();

CREATE INDEX IF NOT EXISTS places_name_trgm_idx ON public.places USING gin (lower(extensions.unaccent(name)) extensions.gin_trgm_ops);
